	// ====================================================================================
	// 0xAE8B70 EmitLine(a, b, pkt): GP0 line packet {len 3, ws+0xF0 (colour | 0x40000000),
	// SXY a, SXY b} (0x10 bytes); OT = ws+0xF4 when non-zero, else rt+0x4C +
	// (((za + zb) / 2) >> 2 & ~3) with z = the u16 depth at vertex +4; depth keys (za, zb, 0, 0).
	// Returns pkt + 0x10.
	static uint8_t *EmitLine_AE8B70(const uint8_t *a, const uint8_t *b, uint8_t *pkt)
	{
		U8(pkt, 3) = 3;
		U32(pkt, 4) = U32(WS(), 0xF0);
		U32(pkt, 8) = U32(a, 0);
		U32(pkt, 0xC) = U32(b, 0);
		uint32_t ot = U32(WS(), 0xF4);
		if (ot == 0)
		{
			// 0xAE8BA8 `mov ax, word [ecx+4]`: the upper half of eax is that of ws+0xF4 (0)
			int32_t zb = U16(b, 4);
			int32_t za = U16(a, 4);
			int32_t k = (zb + za) / 2;                     // cdq; sub eax, edx; sar eax, 1
			k >>= 2;
			uint32_t key = (uint32_t)k & 0xFFFFFFFCu;      // and al, 0xFC
			x::InsertPrimDepthKeys(key + U32(RT(), 0x4C), pkt, za, zb, 0, 0);
			return pkt + 0x10;
		}
		int32_t zb = U16(b, 4);
		int32_t za = U16(a, 4);
		x::InsertPrimDepthKeys(ot, pkt, za, zb, 0, 0);
		return pkt + 0x10;
	}

	// 0xAE8A30 EmitQuadEdges(base, i0, i1, i2, i3): the four edges of a quad as line packets,
	// each edge emitted once per frame through per-vertex edge bits at vertex +6 (byte offsets
	// i0..i3 into the projected vertex array base). The skip tests use the bits read at entry;
	// the edge i0-i2 is always emitted (vanilla). Packet cursor ctx+0x7C.
	static void EmitQuadEdges_AE8A30(uint8_t *base, uint32_t i0, uint32_t i1, uint32_t i2, uint32_t i3)
	{
		uint32_t f2 = U8(base + i2, 6);                   // [ebp+0x14]
		uint32_t f1 = U8(base + i1, 6);                   // [ebp-8]
		uint32_t f3 = U8(base + i3, 6);                   // [ebp-4]
		uint8_t f0 = U8(base + i0, 6);                    // [ebp+0xB]
		uint8_t *pkt = PTR(CTX(), 0x7C);                  // eax
		if ((uint8_t)((f0 & 2) | (f1 & 1)) != 3)
		{
			U8(base + i0, 6) = (uint8_t)(f0 | 2);          // from the value read at entry
			U8(base + i1, 6) |= 1;
			pkt = EmitLine_AE8B70(base + i0, base + i1, pkt);
		}
		if ((uint8_t)((f3 & 4) | (f2 & 8)) != 0xC)
		{
			U8(base + i2, 6) |= 8;
			U8(base + i3, 6) |= 4;
			pkt = EmitLine_AE8B70(base + i2, base + i3, pkt);
		}
		U8(base + i0, 6) |= 4;
		U8(base + i2, 6) |= 1;
		pkt = EmitLine_AE8B70(base + i0, base + i2, pkt);
		if ((uint8_t)((f3 & 2) | (f1 & 8)) != 0xA)
		{
			U8(base + i1, 6) |= 8;
			U8(base + i3, 6) |= 2;
			pkt = EmitLine_AE8B70(base + i1, base + i3, pkt);
		}
		PTR(CTX(), 0x7C) = pkt;
	}

	// 0xAE86F0 (Draw 63 MorphWireframeLines): desc bone+0xB8 = {s16 topology object A, s16 object
	// B (source vertices), s16 object C (target vertices)}. Vertex i (count = A+0x18) =
	// B.v + (C.v - B.v) * bone+0x94 / 256 into the arena scratch ctx+0x74 (8 bytes each), then
	// parent xform scaled by bone+0x8C.. at the parent origin (0xAE8940 == Ifrit 0xB27130 ->
	// h_B27130), each vertex projected (+0 SXY, +4 SZ3, +6 = 0 edge bits). Colour word
	// ws+0xF0 = bone+0xCC | 0x40000000 (GP0 line), OT ws+0xF4 = bone+0xC0 ? rt+0x4C +
	// (bone+0xC0 & 0x3FFC) : 0 (0 = per-line depth). A's primitive list (A + A+8): type 0x10
	// records (0xC bytes, vertex offsets at +4..+0xA) and 0x12 records (0x18 bytes, offsets at
	// +0xC..+0x12) become deduplicated quad edges; any other type ends the list.
	// ------------------------------------------------------------------------------------
	static void __cdecl dh_63_MorphWireframeLines()
	{
		uint8_t *desc = PTR(CUR(), 0xB8);                 // esi
		uint8_t *objA = blob::ObjectPtr(S16(desc, 0));    // [ebp-4]
		uint8_t *objB = blob::ObjectPtr(S16(desc, 2));    // edi
		uint8_t *objC = blob::ObjectPtr(S16(desc, 4));
		uint8_t *dst = objC + U32(objC, 0x14);            // esi: target vertices
		int32_t f = S16(CUR(), 0x94);                     // ebx
		uint8_t *src = objB + U32(objB, 0x14);            // ecx: source vertices
		uint8_t *v = PTR(CTX(), 0x74);                    // edi
		int32_t n = S32(objA, 0x18);
		if (n > 0)
		{
			do
			{
				int32_t d = sub32(S16(dst, 0), S16(src, 0));
				S16(v, 0) = (int16_t)add32(mul32(d, f) / 256, S16(src, 0));
				d = sub32(S16(dst, 2), S16(src, 2));
				S16(v, 2) = (int16_t)add32(mul32(d, f) / 256, S16(src, 2));
				d = sub32(S16(dst, 4), S16(src, 4));
				S16(v, 4) = (int16_t)add32(mul32(d, f) / 256, S16(src, 4));
				src += 8;
				dst += 8;
				v += 8;
			} while (--n != 0);
		}
		h_B27130();
		v = PTR(CTX(), 0x74);                             // esi
		n = S32(objA, 0x18);                              // ebx
		if (n > 0)
		{
			do
			{
				uint32_t xy = ((uint32_t)U16(v, 2) << 16) | (uint32_t)U16(v, 0);
				uint32_t z = U16(v, 4);
				x::GteWriteData((int32_t)xy, 0);
				x::GteWriteData((int32_t)z, 1);
				x::GteRTPS();
				x::GteReadSXY2(v);
				uint16_t sz = GTE_SZ3_LO();
				U16(v, 6) = 0;
				U16(v, 4) = sz;
				v += 8;
			} while (--n != 0);
		}
		U32(WS(), 0xF0) = U32(CUR(), 0xCC) | 0x40000000u;
		int32_t bias = S16(CUR(), 0xC0);
		if (bias == 0)
			U32(WS(), 0xF4) = 0;
		else
			U32(WS(), 0xF4) = ((uint32_t)bias & 0x3FFC) + U32(RT(), 0x4C);
		uint8_t *p = objA + U32(objA, 8);                 // esi: primitive list
		uint8_t *base = PTR(CTX(), 0x74);                 // ebx
		int32_t t = S16(p, 0);
		// 0xAE88A2 / 0xAE8928 `movsx eax, word; cmp eax, 0xFFFF`: never equal (0xFFFF reads as -1);
		// the list really ends on the first type that is neither 0x10 nor 0x12
		if (t == (int32_t)0xFFFF) return;
		for (;;)
		{
			if (t == 0x10)
			{
				int32_t cnt = S16(p, 2);
				p += 4;
				if (cnt > 0)
				{
					do
					{
						EmitQuadEdges_AE8A30(base, U16(p, 4), U16(p, 6), U16(p, 8), U16(p, 0xA));
						p += 0xC;
					} while (--cnt != 0);
				}
			}
			else if (t == 0x12)
			{
				int32_t cnt = S16(p, 2);
				p += 4;
				if (cnt > 0)
				{
					do
					{
						EmitQuadEdges_AE8A30(base, U16(p, 0xC), U16(p, 0xE), U16(p, 0x10), U16(p, 0x12));
						p += 0x18;
					} while (--cnt != 0);
				}
			}
			else
				return;
			t = S16(p, 0);
			if (t == (int32_t)0xFFFF) return;
		}
	}

